#!/usr/bin/env python3
"""Vendors the Iconsax SVGs listed in icons.map and converts them to path data.

Usage: gen_icons.py <icon-library>/icons/rounded/linear

Writes ../src/TaifaMail.App/Assets/Icons/<name>.svg (the vendored files) and
../src/TaifaMail.App/Controls/IconData.cs (stroke geometry strings the
IconView control draws). The library path is only read here, never at runtime.
"""
import math, re, shutil, sys, xml.etree.ElementTree as ET
from pathlib import Path

root = Path(sys.argv[1])
here = Path(__file__).parent
out_svg = here.parent / "src/TaifaMail.App/Assets/Icons"
out_svg.mkdir(parents=True, exist_ok=True)
NS = "{http://www.w3.org/2000/svg}"

def f(x): return ("%.4f" % float(x)).rstrip("0").rstrip(".")

def circle(cx, cy, r):
    return f"M{f(cx-r)},{f(cy)}a{f(r)},{f(r)} 0 1,0 {f(2*r)},0a{f(r)},{f(r)} 0 1,0 {f(-2*r)},0"

def rect(x, y, w, h, rx):
    rx = min(rx, w/2, h/2)
    if rx <= 0:
        return f"M{f(x)},{f(y)}h{f(w)}v{f(h)}h{f(-w)}z"
    return (f"M{f(x+rx)},{f(y)}h{f(w-2*rx)}a{f(rx)},{f(rx)} 0 0 1 {f(rx)},{f(rx)}v{f(h-2*rx)}"
            f"a{f(rx)},{f(rx)} 0 0 1 {f(-rx)},{f(rx)}h{f(-(w-2*rx))}a{f(rx)},{f(rx)} 0 0 1 {f(-rx)},{f(-rx)}"
            f"v{f(-(h-2*rx))}a{f(rx)},{f(rx)} 0 0 1 {f(rx)},{f(-rx)}z")

def shapes(el):
    for e in el.iter():
        tag = e.tag.replace(NS, "")
        if tag == "path": yield e.get("d")
        elif tag == "circle": yield circle(float(e.get("cx")), float(e.get("cy")), float(e.get("r")))
        elif tag == "rect": yield rect(float(e.get("x", 0)), float(e.get("y", 0)), float(e.get("width")), float(e.get("height")), float(e.get("rx", 0)))
        elif tag == "line": yield f"M{e.get('x1')},{e.get('y1')}L{e.get('x2')},{e.get('y2')}"
        elif tag in ("polyline", "polygon"):
            pts = re.findall(r"-?[\d.]+", e.get("points"))
            pairs = list(zip(pts[0::2], pts[1::2]))
            yield "M" + "L".join(f"{a},{b}" for a, b in pairs) + ("z" if tag == "polygon" else "")

entries = []
for raw in (l.strip() for l in (here / "icons.map").read_text().splitlines()):
    if not raw or raw.startswith("#"): continue
    name, rel = [p.strip() for p in raw.split("=")]
    src = root / rel
    shutil.copyfile(src, out_svg / f"{name}.svg")
    tree = ET.parse(src).getroot()
    data = "".join(s for s in shapes(tree) if s)
    entries.append(f'        ["{name}"] = "{data}",')
cs = ("// <auto-generated> by tools/gen_icons.py from the vendored SVGs. Do not edit by hand. </auto-generated>\n"
      "namespace TaifaMail.App.Controls;\n\ninternal static class IconData\n{\n"
      "    public static readonly Dictionary<string, string> Paths = new()\n    {\n" + "\n".join(entries) + "\n    };\n}\n")
(here.parent / "src/TaifaMail.App/Controls/IconData.cs").write_text(cs)
print("icons:", len(entries))
